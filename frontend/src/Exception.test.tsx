function fill(label: string, value: string) { fireEvent.change(screen.getByLabelText(label, { exact: true }), { target: { value } }) }
function review(kind: 'request' | 'resolve' = 'request', reason = rawReason) {
  fireEvent.click(screen.getByRole('button', { name: kind === 'request' ? '要求補件' : '處置異常' }))
  fill(kind === 'request' ? '補件要求（司機可見）' : '處置原因（司機可見）', reason)
  fireEvent.click(screen.getByRole('button', { name: kind === 'request' ? '檢視補件要求確認' : '檢視異常處置確認' }))
}
function confirm(kind: 'request' | 'resolve' = 'request') { fireEvent.click(screen.getByRole('button', { name: kind === 'request' ? '確認要求補件' : '確認處置異常' })) }
async function openManager(extra = {}) {
  const view = render(<ExceptionManager onExpired={vi.fn()} {...extra} />)
  fireEvent.click(await screen.findByRole('button', { name: `開啟異常 ${exceptionRow().taskNo}` }))
  await screen.findByRole('region', { name: '目前異常資料' })
  return view
}
