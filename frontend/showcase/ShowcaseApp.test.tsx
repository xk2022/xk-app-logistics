    click('展示完成並釋放'); confirm()
    expect(screen.getByRole('region', { name: '展示任務完成紀錄' })).toHaveTextContent('尚待管理確認')
    expect(screen.queryByRole('button', { name: '加入合成任務照片' })).not.toBeInTheDocument()
    role('DISPATCHER'); nav('確認與結案')
    const closure = screen.getByRole('article', { name: `展示結案 ${orderNo}` })
    expect(within(closure).getByRole('button', { name: '展示結案' })).toBeDisabled()
