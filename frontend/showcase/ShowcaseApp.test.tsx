import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import ShowcaseApp from './ShowcaseApp'

const orderNo = 'DEMO-LOCAL-1001'
const taskNo = 'T-DEMO-1001'
const raw = ' 合成 e\u0301\0原文\n第二行 '
function click(name: string) { fireEvent.click(screen.getByRole('button', { name })) }
function nav(name: string) { fireEvent.click(within(screen.getByRole('navigation', { name: '主要導覽' })).getByRole('button', { name })) }
function role(value: 'ADMIN' | 'DISPATCHER' | 'DRIVER') { fireEvent.change(screen.getByLabelText('展示角色'), { target: { value } }) }
function order(no = orderNo) { return screen.getByRole('article', { name: `展示訂單 ${no}` }) }
function driverTask() { return screen.getByRole('article', { name: `本人任務 ${taskNo}` }) }
function confirm() { fireEvent.click(within(screen.getByRole('dialog', { name: '確認展示操作' })).getByRole('button', { name: '確認執行展示操作' })) }
function accept() { nav('訂單工作台'); fireEvent.click(within(order()).getByRole('button', { name: '展示受理' })); confirm() }
function assign() { nav('調度工作台'); const row = screen.getByRole('article', { name: `展示派工 ${taskNo}` }); fireEvent.change(within(row).getByLabelText('展示拖板'), { target: { value: 'trailer-1' } }); fireEvent.click(within(row).getByRole('button', { name: '建立展示派工' })); confirm() }
function depart() { role('DRIVER'); nav('本人運輸任務'); fireEvent.click(within(driverTask()).getByRole('button', { name: '展示出發' })); confirm() }
function progress() { const row = driverTask(); fireEvent.click(within(row).getByRole('button', { name: '加入合成任務照片' })); fireEvent.click(within(row).getByLabelText('選取進度照片 1')); fireEvent.click(within(row).getByRole('button', { name: '提交展示進度' })); confirm() }
function describeAndReport(text = raw) { fireEvent.change(screen.getByLabelText('展示異常描述'), { target: { value: text } }); click('回報展示異常'); confirm() }

beforeEach(() => { vi.stubGlobal('fetch', vi.fn()) })
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals() })

