    expect(screen.getByText('待管理處置')).toBeVisible()
    expect(screen.getByRole('button', { name: '展示完成並釋放' })).toBeDisabled()
    role('ADMIN'); nav('異常處理')
    fireEvent.change(screen.getByLabelText('處置原因（司機可見）'), { target: { value: ' 合成管理處置 e\u0301\0 ' } })
    click('處置展示異常'); confirm()
    expect(screen.getByLabelText('展示處置原因原文').textContent).toBe(' 合成管理處置 e\u0301\0 ')
    role('DRIVER'); nav('本人運輸任務')
    fireEvent.click(screen.getByLabelText('我確認展示任務完成並解除合成資源占用'))
    expect(screen.getByLabelText('我確認展示任務完成並解除合成資源占用')).toBeChecked()
